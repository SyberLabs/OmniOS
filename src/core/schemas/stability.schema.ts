// ============================================
// STABILITY ENGINE
// ============================================

export interface StabilityResult {
    score: number;
    breakdown: EffectBreakdown[];
    triggeredRules: TriggeredRule[];
    alerts: Alert[];
}

export interface EffectBreakdown {
    effectId: string;
    attributeId: string;
    attributeValue: number;
    contribution: number;
    description?: string;
}

export interface TriggeredRule {
    ruleId: string;
    ruleName: string;
    action: RuleAction;
}

export interface Alert {
    message: string;
    severity: 'info' | 'warning' | 'critical';
    ruleId: string;
}

/**
 * Computes stability score from attributes and model
 */
export function computeStability(
    attributes: SystemAttribute[],
    model: SystemModel
): StabilityResult {
    const breakdown: EffectBreakdown[] = [];
    const triggeredRules: TriggeredRule[] = [];
    const alerts: Alert[] = [];

    let score = model.baseStability;

    // Create attribute lookup map
    const attrMap = new Map(attributes.map(a => [a.id, a.value]));

    // Apply each effect
    for (const effect of model.effects) {
        const attrValue = attrMap.get(effect.attributeId);
        if (attrValue === undefined) continue;

        let contribution = calculateEffect(attrValue, effect);

        // Apply direction
        if (effect.direction === 'negative') {
            contribution = -contribution;
        }

        score += contribution;

        breakdown.push({
            effectId: effect.id,
            attributeId: effect.attributeId,
            attributeValue: attrValue,
            contribution,
            description: effect.description
        });
    }

    // Evaluate rules
    for (const rule of model.rules.filter(r => r.isActive).sort((a, b) => b.priority - a.priority)) {
        if (evaluateCondition(rule.condition, attrMap)) {
            triggeredRules.push({
                ruleId: rule.id,
                ruleName: rule.name,
                action: rule.action
            });

            // Apply action
            if (rule.action.type === 'modify_stability' && rule.action.stabilityDelta) {
                score += rule.action.stabilityDelta;
            }

            if (rule.action.type === 'add_alert' && rule.action.alertMessage) {
                alerts.push({
                    message: rule.action.alertMessage,
                    severity: rule.action.alertSeverity || 'info',
                    ruleId: rule.id
                });
            }
        }
    }

    // Clamp to bounds
    score = Math.max(model.minStability, Math.min(model.maxStability, score));

    return { score, breakdown, triggeredRules, alerts };
}

/**
 * Calculate the numeric effect contribution
 */
function calculateEffect(value: number, effect: AttributeEffect): number {
    switch (effect.effectType) {
        case 'linear':
            return value * effect.coefficient;

        case 'exponential':
            return Math.pow(value / 100, effect.exponent || 2) * 100 * effect.coefficient;

        case 'threshold':
            return value > (effect.threshold || 50)
                ? (effect.highValue || 10)
                : (effect.lowValue || 0);

        case 'inverse':
            return value > 0 ? (effect.coefficient / value) * 100 : 0;

        case 'logarithmic':
            return value > 0 ? Math.log(value + 1) * effect.coefficient : 0;

        case 'custom':
            if (effect.customExpression) {
                try {
                    // Safe evaluation with limited scope
                    const fn = new Function('value', `return ${effect.customExpression}`);
                    return fn(value) * effect.coefficient;
                } catch {
                    return 0;
                }
            }
            return 0;

        default:
            return 0;
    }
}

/**
 * Evaluate a condition expression against attributes
 */
function evaluateCondition(condition: string, attrMap: Map<string, number>): boolean {
    try {
        // Build variable context
        const context: Record<string, number> = {};
        for (const [id, value] of attrMap) {
            // Convert attribute IDs to valid JS identifiers
            const varName = id.replace(/[^a-zA-Z0-9_]/g, '_');
            context[varName] = value;
        }

        // Create function with context
        const varNames = Object.keys(context);
        const varValues = Object.values(context);
        const fn = new Function(...varNames, `return ${condition}`);

        return Boolean(fn(...varValues));
    } catch {
        console.warn(`Failed to evaluate condition: ${condition}`);
        return false;
    }
}

