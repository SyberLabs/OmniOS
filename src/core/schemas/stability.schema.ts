// ============================================

/**
 * Effect type determines the mathematical relationship
 */
export type EffectType =
    | 'linear'       // value * coefficient
    | 'exponential'  // value^exponent * coefficient
    | 'threshold'    // value > threshold ? highValue : lowValue
    | 'inverse'      // coefficient / value
    | 'logarithmic'  // log(value) * coefficient
    | 'custom';      // user-defined expression

/**
 * Defines how an attribute affects stability
 */
export interface AttributeEffect {
    /** Unique effect ID */
    id: string;

    /** ID of the attribute this applies to */
    attributeId: string;

    /** Type of mathematical relationship */
    effectType: EffectType;

    /** Direction of effect on stability */
    direction: 'positive' | 'negative';

    /** Main coefficient/weight */
    coefficient: number;

    /** For threshold type: the trigger value */
    threshold?: number;

    /** For threshold type: value above threshold */
    highValue?: number;

    /** For threshold type: value below threshold */
    lowValue?: number;

    /** For exponential type: the exponent */
    exponent?: number;

    /** For custom type: JavaScript expression */
    customExpression?: string;

    /** Human-readable description */
    description?: string;
}

/**
 * A rule that modifies stability based on conditions
 */
export interface StabilityRule {
    /** Unique rule ID */
    id: string;

    /** Rule name */
    name: string;

    /** Condition expression (JS-like) */
    condition: string;

    /** Action when condition is true */
    action: RuleAction;

    /** Priority (higher = evaluated first) */
    priority: number;

    /** Is rule active? */
    isActive: boolean;

    /** Generated by LLM survey? */
    isLLMGenerated?: boolean;
}

/**
 * Action to take when rule condition is met
 */
export interface RuleAction {
    type: 'modify_stability' | 'add_alert' | 'trigger_notification' | 'chain_rule';

    /** For modify_stability: amount to add/subtract */
    stabilityDelta?: number;

    /** For add_alert: alert message */
    alertMessage?: string;

    /** For add_alert: severity level */
    alertSeverity?: 'info' | 'warning' | 'critical';

    /** For chain_rule: ID of next rule to evaluate */
    chainRuleId?: string;
}

/**
 * Complete system model configuration
 */
export interface SystemModel {
    /** System this model belongs to */
    systemId: SystemType;

    /** Base stability score (before effects) */
    baseStability: number;

    /** Attribute effects */
    effects: AttributeEffect[];

    /** Stability rules */
    rules: StabilityRule[];

    /** Minimum stability floor */
    minStability: number;

    /** Maximum stability ceiling */
    maxStability: number;
}

